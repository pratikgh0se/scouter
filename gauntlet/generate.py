"""The generator gate (spec 2.2): expand every layer through the adapter,
check ids, tiers and counts, and write cases.jsonl + generation.md."""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass, field
from pathlib import Path

from gauntlet.adapter import Adapter, LayerSpec
from gauntlet.case import Case
from gauntlet.store import RunDir, atomic_write_text
from gauntlet.subset import stratified_subset

COUNT_TOLERANCE = 0.02


#: Files (relative to the working directory) whose content decides what
#: generation produces: the layer generators, their data tables, the config.
FINGERPRINT_GLOBS = ("tests/gauntlet/layers/*.py", "tests/gauntlet/data/*.json", "gauntlet.json")
FINGERPRINT_NAME = "generator-fingerprint.txt"


def generator_fingerprint(root: Path | None = None) -> str:
    """sha256 over the generator inputs (names and bytes, sorted). A run dir
    whose recorded fingerprint differs from this was generated by older (or
    different) harness code: its cases.jsonl is stale (the L7 incident)."""
    base = Path(root) if root else Path.cwd()
    h = hashlib.sha256()
    files = sorted({p for g in FINGERPRINT_GLOBS for p in base.glob(g) if p.is_file()})
    for p in files:
        h.update(p.relative_to(base).as_posix().encode() + b"\0" + p.read_bytes() + b"\0")
    return h.hexdigest()


def stale_cases_reason(run: RunDir, root: Path | None = None) -> str | None:
    """None when the run's cases.jsonl matches the current generator inputs;
    otherwise a one-line reason (no fingerprint recorded, or it differs)."""
    f = run.root / FINGERPRINT_NAME
    if not f.exists():
        return "no generator fingerprint recorded (cases.jsonl predates the stale-cases guard)"
    recorded, current = f.read_text(encoding="utf-8").strip(), generator_fingerprint(root)
    if recorded != current:
        return (
            f"generator inputs changed since generate "
            f"(recorded {recorded[:12]}, now {current[:12]})"
        )
    return None


class GenerationError(ValueError):
    pass


@dataclass
class LayerCount:
    spec: LayerSpec
    got: int
    tiers: dict[str, int] = field(default_factory=dict)
    unmapped_p2: list[str] = field(default_factory=list)


def check_layer(spec: LayerSpec, cases: list[Case]) -> LayerCount:
    errors: list[str] = []
    for c in cases:
        if c.layer != spec.name:
            errors.append(f"{c.id}: layer {c.layer!r} generated under {spec.name!r}")
        if c.meta.get("unmapped") and c.tier in ("P0", "P1"):
            errors.append(
                f"{c.id}: {c.tier} case falls through to unmapped " f"({c.meta['unmapped']})"
            )
    want = spec.expected_count
    if want and abs(len(cases) - want) > COUNT_TOLERANCE * want:
        errors.append(f"layer {spec.name}: {len(cases)} cases, formula says {want} (> 2% off)")
    if errors:
        raise GenerationError(
            "; ".join(errors[:20]) + (f" (+{len(errors) - 20} more)" if len(errors) > 20 else "")
        )
    tiers: dict[str, int] = {}
    for c in cases:
        tiers[c.tier] = tiers.get(c.tier, 0) + 1
    return LayerCount(spec, len(cases), tiers, [c.id for c in cases if c.meta.get("unmapped")])


def generate_all(
    adapter: Adapter,
    layers: list[str] | None = None,
    *,
    subset: int | None = None,
    subset_layer: str | None = None,
    subset_keys: list[str] | None = None,
    seed: int = 0,
) -> tuple[list[Case], list[LayerCount], dict | None]:
    """(row 501 item H, fix round 1): when `subset` is given, `subset_layer`
    is generated and VALIDATED in full first (check_layer runs against the
    complete, unsubsetted list -- the count gate that catches a real
    generation bug must never be weakened by subsetting), and only then
    replaced by a deterministic, seeded, multi-axis stratified subset of
    itself (`gauntlet.subset.stratified_subset`, keyed on
    `case.meta[k] for k in subset_keys`). Every other layer is
    untouched. Returns the subset's own record (for the caller to persist,
    e.g. into progress.json) or None when no subset was requested."""
    specs = sorted(adapter.layers(), key=lambda s: s.order)
    if layers:
        unknown = set(layers) - {s.name for s in specs}
        if unknown:
            raise GenerationError(f"unknown layers: {sorted(unknown)}")
        specs = [s for s in specs if s.name in layers]
    all_cases: list[Case] = []
    counts: list[LayerCount] = []
    seen: set[str] = set()
    subset_record: dict | None = None
    for spec in specs:
        cases = adapter.generate(spec.name)
        #: Duplicate detection over the FULL, unsubsetted `cases` -- both
        #: within this layer's own batch and against every earlier layer.
        #: (Fix round 1: subsetting removing a within-layer duplicate by
        #: chance must never silently defeat this check -- it now runs
        #: entirely before any subsetting happens.)
        ids = [c.id for c in cases]
        dup = sorted({i for i in ids if ids.count(i) > 1} | (set(ids) & seen))
        if dup:
            raise GenerationError(f"duplicate case ids in {spec.name}: {dup[:5]}")
        seen.update(ids)
        counts.append(check_layer(spec, cases))
        if subset is not None and spec.name == subset_layer:
            full_n = len(cases)
            keys = subset_keys or []
            key_fns = [(lambda c, k=k: c.meta.get(k)) for k in keys]
            cases = stratified_subset(cases, subset, seed, key_fns)
            subset_record = {
                "layer": subset_layer,
                "size": len(cases),
                "of": full_n,
                "seed": seed,
                "keys": keys,
            }
        all_cases.extend(cases)
    return all_cases, counts, subset_record


def generation_md(
    adapter: Adapter, counts: list[LayerCount], cases: list[Case], subset_record: dict | None = None
) -> str:
    lines = [
        f"# Generation: {adapter.name}",
        "",
        "| # | Layer | Formula | Generated | P0 | P1 | P2 | Live |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for c in counts:
        s = c.spec
        lines.append(
            f"| {s.order} | {s.name} | {s.expected_count} | {c.got} | "
            f"{c.tiers.get('P0', 0)} | {c.tiers.get('P1', 0)} | "
            f"{c.tiers.get('P2', 0)} | {'yes' if s.live else 'no'} |"
        )
    total = sum(c.got for c in counts)
    lines += [
        "",
        f"**Total:** {total} cases " f"({sum(c.got for c in counts if c.spec.live)} live).",
        "",
    ]
    if subset_record:
        lines += [
            f"**Subset:** layer `{subset_record['layer']}` generated "
            f"{subset_record['of']}, kept {subset_record['size']} "
            f"(stratified on {subset_record['keys']}, seed {subset_record['seed']}) "
            "-- the layer table above and this run's cases.jsonl differ by design.",
            "",
        ]
    unmapped = [i for c in counts for i in c.unmapped_p2]
    if unmapped:
        lines += ["## P2 cases with no mapping", ""] + [f"- `{i}`" for i in unmapped] + [""]
    notes = adapter.generation_notes(cases)
    if notes:
        lines += [notes.rstrip(), ""]
    return "\n".join(lines)


def write_generation(
    run: RunDir,
    adapter: Adapter,
    layers: list[str] | None = None,
    *,
    subset: int | None = None,
    subset_layer: str | None = None,
    subset_keys: list[str] | None = None,
    seed: int = 0,
) -> list[LayerCount]:
    cases, counts, subset_record = generate_all(
        adapter,
        layers,
        subset=subset,
        subset_layer=subset_layer,
        subset_keys=subset_keys,
        seed=seed,
    )
    run.ensure()
    run.write_cases(cases)
    atomic_write_text(run.root / FINGERPRINT_NAME, generator_fingerprint() + "\n")
    atomic_write_text(run.generation_md, generation_md(adapter, counts, cases, subset_record))
    if subset_record:
        atomic_write_text(run.subset_json, json.dumps(subset_record) + "\n")
    return counts
